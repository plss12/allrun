// Builds the font the screens draw their icons with, from the same SVG paths the images draw:
//
//   assets/fonts/allrun-icons.otf         one glyph per icon
//   src/ui/icons/icon-font.generated.ts   which character is each icon
//
// A font and not a Skia canvas per icon: on Android each canvas is a texture of its own, to create
// and to compose on every frame, and a screen has dozens of icons (see ADR 014). A text is there on
// the first frame, in the middle of a box of its size. Needs uv, which runs fontTools.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const FONT = join(ROOT, 'assets', 'fonts', 'allrun-icons.otf');
const MAP = join(ROOT, 'src', 'ui', 'icons', 'icon-font.generated.ts');
/** The first character of Unicode's private use area. */
const FIRST_CHARACTER = 0xe000;

/** The icons of one `export const NAME = { key: 'path', ... }` of a generated file. */
function pathsOf(file, constant) {
  const source = readFileSync(join(ROOT, file), 'utf8');
  const start = source.indexOf(`export const ${constant} = {`);
  if (start < 0) {
    throw new Error(`No ${constant} in ${file}`);
  }
  const body = source.slice(start, source.indexOf('\n}', start));
  const icons = [...body.matchAll(/^\s*'?([\w-]+)'?:\s*'([^']+)'/gm)].map(([, key, path]) => ({
    key,
    path,
  }));
  if (icons.length === 0) {
    throw new Error(`No icons in ${constant} of ${file}`);
  }
  return icons;
}

const families = [
  // Already in the middle of their boxes: `npm run icons` moves them there, and a test checks it.
  {
    id: 'ui',
    icons: pathsOf('src/ui/icons/ui-icons.generated.ts', 'UI_ICON_PATHS'),
    center: false,
  },
  // On screen they go in the middle of their boxes by their shape, as the interface's.
  {
    id: 'sport',
    icons: pathsOf('src/editor/icons/sport-icons.generated.ts', 'SPORT_ICON_PATHS'),
    center: true,
  },
];

let next = FIRST_CHARACTER;
const glyphs = families.flatMap(({ id, icons, center }) =>
  icons.map(({ key, path }) => ({
    family: id,
    key,
    path,
    center,
    unicode: next++,
    name: `${id}.${key}`.replaceAll('-', '_'),
  })),
);

mkdirSync(dirname(FONT), { recursive: true });
execFileSync(
  'uv',
  [
    'run',
    '--no-project',
    '--with',
    'fonttools',
    'python',
    '-I',
    join(ROOT, 'scripts', 'icons', 'build-icon-font.py'),
    FONT,
  ],
  { input: JSON.stringify(glyphs), stdio: ['pipe', 'inherit', 'inherit'] },
);

const entries = (id) =>
  glyphs
    .filter(({ family }) => family === id)
    .map(({ key, unicode }) => `  '${key}': '\\u${unicode.toString(16).toUpperCase()}',`)
    .join('\n');
const source = `// Generated by scripts/icons/build-icon-font.mjs (npm run icons). Do not edit.

/** The character of each icon of the interface in assets/fonts/allrun-icons.otf. */
export const UI_ICON_CHARACTERS = {
${entries('ui')}
} as const;

/** The character of each sport's icon in assets/fonts/allrun-icons.otf. */
export const SPORT_ICON_CHARACTERS = {
${entries('sport')}
} as const;
`;
writeFileSync(MAP, await format(source, { ...(await resolveConfig(MAP)), filepath: MAP }));
console.log(`${glyphs.length} icons in ${FONT}`);
